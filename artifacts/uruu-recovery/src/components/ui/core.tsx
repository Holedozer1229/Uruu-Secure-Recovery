const Badge = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement> & { variant?: "default" | "secondary" | "outline" | "destructive" }>(
  ({ className, variant = "default", ...props }, ref) => {
    const variants = {
      default: "border-transparent bg-primary/10 text-primary border border-primary/20 shadow-[0_0_10px_rgba(0,229,255,0.1)]",
      secondary: "border-transparent bg-secondary/10 text-secondary border border-secondary/20 shadow-[0_0_10px_rgba(255,179,0,0.1)]",
      destructive: "border-transparent bg-destructive/10 text-destructive border border-destructive/20 shadow-[0_0_10px_rgba(239,68,68,0.1)]",
      outline: "text-foreground border border-border",
    }
    return (
      <div
        ref={ref}
        className={cn(
          "inline-flex items-center rounded-full px-2.5 py-0.5 text-xs font-semibold transition-colors focus:outline-none focus:ring-2 focus:ring-ring focus:ring-offset-2",
          variants[variant],
          className
        )}
        {...props}
      />
    )
  }
)
Badge.displayName = "Badge"

