/**
 * Prometheus Metrics Routes
 * Exports application metrics in both JSON (for UI) and text/plain (for scrapers).
 */

import { Router, type IRouter } from "express";
import { count, eq, avg, sql } from "drizzle-orm";
import { db, recoveryRequestsTable, guardianApprovalsTable, eventsTable } from "@workspace/db";

const router: IRouter = Router();

// Track request counts in-process
let totalApiRequests = 0;
let apiErrors = 0;
const startTime = Date.now();

export function incrementApiRequests() {
  totalApiRequests++;
}
export function incrementApiErrors() {
  apiErrors++;
}

interface MetricSample {
  name: string;
  help: string;
  type: string;
  value: number;
  labels: string;
}

async function gatherMetrics(): Promise<MetricSample[]> {
  const [totalRequests, byStatus, totalEvents, totalApprovals, avgApproval] = await Promise.all([
    db.select({ count: count() }).from(recoveryRequestsTable),
    db
      .select({ status: recoveryRequestsTable.status, count: count() })
      .from(recoveryRequestsTable)
      .groupBy(recoveryRequestsTable.status),
    db.select({ count: count() }).from(eventsTable),
    db.select({ count: count() }).from(guardianApprovalsTable),
    db
      .select({
        avg: avg(
          sql<number>`EXTRACT(EPOCH FROM (${recoveryRequestsTable.updatedAt} - ${recoveryRequestsTable.createdAt}))`
        ),
      })
      .from(recoveryRequestsTable)
      .where(eq(recoveryRequestsTable.status, "FINALIZED")),
  ]);

  const total = Number(totalRequests[0]?.count ?? 0);
  const events = Number(totalEvents[0]?.count ?? 0);
  const approvals = Number(totalApprovals[0]?.count ?? 0);
  const avgTime = Number(avgApproval[0]?.avg ?? 0);
  const uptimeSeconds = (Date.now() - startTime) / 1000;

  const statusCounts: Record<string, number> = {};
  for (const row of byStatus) {
    statusCounts[row.status] = Number(row.count);
  }

  const finalized = statusCounts["FINALIZED"] ?? 0;
  const approvalRate = total > 0 ? finalized / total : 0;

  const metrics: MetricSample[] = [
    // Recovery request metrics
    {
      name: "uruu_recovery_requests_total",
      help: "Total number of recovery requests initiated",
      type: "counter",
      value: total,
      labels: "",
    },
    ...Object.entries(statusCounts).map(([status, cnt]) => ({
      name: "uruu_recovery_requests_by_status",
      help: "Recovery requests grouped by current status",
      type: "gauge",
      value: cnt,
      labels: `status="${status}"`,
    })),
    {
      name: "uruu_recovery_approval_rate",
      help: "Fraction of recovery requests that have been finalized",
      type: "gauge",
      value: approvalRate,
      labels: "",
    },
    {
      name: "uruu_recovery_avg_finalization_seconds",
      help: "Average time from initiation to finalization in seconds",
      type: "gauge",
      value: avgTime,
      labels: "",
    },
    // Guardian metrics
    {
      name: "uruu_guardian_approvals_total",
      help: "Total guardian approval transactions recorded",
      type: "counter",
      value: approvals,
      labels: "",
    },
    // Event log metrics
    {
      name: "uruu_events_total",
      help: "Total number of protocol events emitted",
      type: "counter",
      value: events,
      labels: "",
    },
    // API metrics
    {
      name: "uruu_api_requests_total",
      help: "Total HTTP requests handled by API server",
      type: "counter",
      value: totalApiRequests,
      labels: "",
    },
    {
      name: "uruu_api_errors_total",
      help: "Total HTTP 4xx/5xx errors returned by API server",
      type: "counter",
      value: apiErrors,
      labels: "",
    },
    // zkEVM simulation metrics
    {
      name: "uruu_zkevm_proofs_generated_total",
      help: "Total ZK proofs generated by the zkEVM pipeline (simulated)",
      type: "counter",
      value: total * 3 + 142,
      labels: "",
    },
    {
      name: "uruu_zkevm_avg_proving_ms",
      help: "Average proof generation time in milliseconds (simulated)",
      type: "gauge",
      value: 1847.3,
      labels: "",
    },
    {
      name: "uruu_zkevm_queue_depth",
      help: "Current zkEVM proof queue depth (simulated)",
      type: "gauge",
      value: Math.floor(Date.now() / 10000) % 8,
      labels: "",
    },
    // System metrics
    {
      name: "uruu_process_uptime_seconds",
      help: "API server uptime in seconds",
      type: "counter",
      value: Math.round(uptimeSeconds),
      labels: "",
    },
    {
      name: "uruu_evm_contract_guardian_count",
      help: "Number of registered guardians on EVM contract (simulated)",
      type: "gauge",
      value: 5,
      labels: `chain="evm"`,
    },
    {
      name: "uruu_evm_contract_guardian_count",
      help: "Number of registered guardians on Solana contract (simulated)",
      type: "gauge",
      value: 5,
      labels: `chain="solana"`,
    },
  ];

  return metrics;
}

// JSON endpoint for the dashboard UI
router.get("/prometheus/metrics", async (_req, res): Promise<void> => {
  const metrics = await gatherMetrics();
  res.json({
    generatedAt: new Date().toISOString(),
    metrics,
  });
});

// Raw Prometheus text format for actual scrapers
router.get("/metrics", async (_req, res): Promise<void> => {
  const metrics = await gatherMetrics();

  const lines: string[] = [];
  const seen = new Set<string>();

  for (const m of metrics) {
    if (!seen.has(m.name)) {
      lines.push(`# HELP ${m.name} ${m.help}`);
      lines.push(`# TYPE ${m.name} ${m.type}`);
      seen.add(m.name);
    }
    const labelStr = m.labels ? `{${m.labels}}` : "";
    lines.push(`${m.name}${labelStr} ${m.value}`);
  }

  res.setHeader("Content-Type", "text/plain; version=0.0.4");
  res.send(lines.join("\n") + "\n");
});

export default router;
